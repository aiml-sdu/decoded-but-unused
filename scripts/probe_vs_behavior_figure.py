"""Make a probe-vs-behavior scatter figure showing the cross-model
dissociation: same probe accuracy in every model but very different
behavioral S-C effects.

Reads from the cross-model summaries we already have.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

# Hardcoded results from the runs we have so far. Updated as data lands.
ROWS = [
    # (model, family, params_B, S_C_mean, probe_acc)
    ("Gemma-3-4B-IT",    "Gemma-3", 4,   8.96, 0.983),
    ("Gemma-2-9B-IT",    "Gemma-2", 9,   6.61, 0.992),
    ("Gemma-3-12B-IT",   "Gemma-3", 12,  11.56, 0.992),
    ("Qwen-2.5-7B-Inst", "Qwen-2.5", 7,  13.35, 0.992),
    ("Qwen-2.5-14B-Inst","Qwen-2.5", 14, 17.89, 0.992),
    ("Gemma-2-27B-IT",   "Gemma-2", 27,  4.47, 0.992),
    ("Llama-3.1-8B-Inst","Llama-3.1", 8, 3.60, None),  # probe acc tbd
]


def main() -> None:
    out_dir = Path("runs/probe_vs_behavior")
    out_dir.mkdir(parents=True, exist_ok=True)

    # Write CSV (will be regenerated as data lands)
    with (out_dir / "probe_vs_behavior.csv").open("w") as f:
        w = csv.writer(f)
        w.writerow(["model", "family", "params_B", "S_C_mean", "probe_acc"])
        for r in ROWS:
            w.writerow(r)

    # Compose pgfplots tex snippet
    tex = []
    tex.append("% probe-vs-behavior scatter; auto-generated by scripts/probe_vs_behavior_figure.py")
    tex.append(r"\begin{tikzpicture}")
    tex.append(r"\begin{axis}[")
    tex.append(r"  width=\columnwidth, height=4.5cm,")
    tex.append(r"  xlabel={Probe accuracy (peak)}, ylabel={Paired $S{-}C$ shift},")
    tex.append(r"  xmin=0.96, xmax=1.0, ymin=0, ymax=20,")
    tex.append(r"  legend pos=north west,")
    tex.append(r"  font=\footnotesize, mark size=2pt,")
    tex.append(r"]")
    family_color = {
        "Gemma-3": "blue!70!black",
        "Gemma-2": "red!70!black",
        "Qwen-2.5": "green!50!black",
        "Llama-3.1": "orange!70!black",
    }
    for fam in family_color:
        rows = [r for r in ROWS if r[1] == fam and r[4] is not None]
        if not rows:
            continue
        tex.append(rf"\addplot+[only marks, color={family_color[fam]}, mark=*] coordinates {{")
        for r in rows:
            tex.append(f"  ({r[4]:.4f}, {r[3]:.2f})  % {r[0]} ({r[2]}B)")
        tex.append(r"};")
        tex.append(rf"\addlegendentry{{{fam}}}")
    tex.append(r"\end{axis}")
    tex.append(r"\end{tikzpicture}")
    (out_dir / "probe_vs_behavior.tex").write_text("\n".join(tex) + "\n")
    print("wrote probe_vs_behavior.csv and probe_vs_behavior.tex")
    print("ROWS:")
    for r in ROWS:
        print(" ", r)


if __name__ == "__main__":
    main()
